#!/usr/bin/env node
// Renders web/nginx.conf from web/security-headers.json (the single source of the web security headers).
//   node tools/gen-nginx-conf.mjs          write web/nginx.conf
//   node tools/gen-nginx-conf.mjs --check  exit 1 if web/nginx.conf is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function renderNginxConf(spec) {
  const headerLines = (indent) =>
    Object.entries(spec.headers)
      .map(([k, v]) => `${indent}add_header ${k} "${String(v).replaceAll('"', '\\"')}" always;`)
      .join('\n');
  const h2 = headerLines('        ');
  return `# GENERATED by web/tools/gen-nginx-conf.mjs from web/security-headers.json - do not edit by hand.
# Serves the built SPA and reverse-proxies the API so the browser sees ONE origin
# (cookies are SameSite=Strict and the API emits no CORS headers).
worker_processes auto;
pid /tmp/nginx.pid;

events {
  worker_connections 1024;
}

http {
  include /etc/nginx/mime.types;
  default_type application/octet-stream;
  server_tokens off;
  sendfile on;
  client_max_body_size 64k;
  client_body_temp_path /tmp/client_temp;
  proxy_temp_path /tmp/proxy_temp;
  fastcgi_temp_path /tmp/fastcgi_temp;
  uwsgi_temp_path /tmp/uwsgi_temp;
  scgi_temp_path /tmp/scgi_temp;
  access_log /dev/stdout;
  error_log /dev/stderr warn;

  server {
    listen 8080;
    server_name _;
    root /usr/share/nginx/html;

    # Security headers are added per static location (API responses carry the API's own headers;
    # nginx add_header inheritance would otherwise duplicate them on proxied responses).
    location = /index.html {
${h2}
        add_header Cache-Control "${spec.cacheControl['index.html']}" always;
    }

    location /assets/ {
${h2}
        add_header Cache-Control "${spec.cacheControl.assets}" always;
        try_files $uri =404;
    }

    location /api/ {
        proxy_pass http://api:3001;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        # Overwrite (never append) so clients cannot inject addresses into X-Forwarded-For.
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto $scheme;
    }

    location = /healthz {
        proxy_pass http://api:3001;
    }

    location / {
${h2}
        add_header Cache-Control "${spec.cacheControl['index.html']}" always;
        try_files $uri /index.html;
    }
  }
}
`;
}

function main() {
  const spec = JSON.parse(readFileSync(path.join(webDir, 'security-headers.json'), 'utf8'));
  const out = renderNginxConf(spec);
  const target = path.join(webDir, 'nginx.conf');
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      current = '';
    }
    if (current.replaceAll('\r\n', '\n') !== out) {
      console.error('web/nginx.conf is out of date: run npm run gen:headers -w web');
      process.exit(1);
    }
    console.log('nginx.conf: up to date');
    return;
  }
  writeFileSync(target, out);
  console.log('wrote web/nginx.conf');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
